    public void validar() {
        try {
            this.descricao = campoDescricaoDespesa.getText().trim();
            this.valor = Double.parseDouble(campoValorDespesa.getText().trim().replace(",", "."));
            this.fixa = (comboBoxTipoDespesa.getSelectedIndex() == 0);
            this.participantesSelecionados = listaParticipantesDespesa.getSelectedValuesList();
            
            Despesa d = (isFixa())
                    ? new DespesaFixa(getDescricao(), getValor(), getParticipantesSelecionados())
                    : new DespesaPorPessoa(getDescricao(), getValor(), getParticipantesSelecionados());

            if (getDescricao().isBlank()) {
                throw new IllegalArgumentException("Informe a descrição.");
            }
            if (getValor()<=0) {
                throw new IllegalArgumentException("O valor da despesa deve ser maior que zero.");
            }
            if (getParticipantesSelecionados().isEmpty()) {
               
                throw new IllegalArgumentException("Selecione ao menos um participante.");
            } else {
                this.valido = true;
                JOptionPane.showMessageDialog(rootPane,
                        "Despesa salva com sucesso");
                this.dispose();
            }
        } catch (NumberFormatException e) {
            exibirErro("Código e Orçamento devem ser numéricos.");
        } catch (Exception e) {
            exibirErro("Houve um erro ao salvar o planejamento: " + e.getMessage());
        }
    }

    private void exibirErro(String msg) {
        JOptionPane.showMessageDialog(this, "Erro: " + msg, "Erro", JOptionPane.ERROR_MESSAGE);
    }

