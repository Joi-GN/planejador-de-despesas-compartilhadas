    public void validar() {
        try {
            this.nomePlanejamento = campoNomeNovoPlanejamento.getText().trim();
            if (this.getNome().isBlank()) {
                JOptionPane.showMessageDialog(rootPane,
                        "Campo do nome vazio");
            } else {
                this.valido = true;
                JOptionPane.showMessageDialog(rootPane,
                        "Planejamento salvo com sucesso");
                this.dispose();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane,
                    "Houve um erro ao salvar o planejamento: " + e.getMessage());
        }
    }
    
    public boolean isValido(){
        return this.valido;
    }

    public String getNome() {
        return this.nomePlanejamento;
    }
    
